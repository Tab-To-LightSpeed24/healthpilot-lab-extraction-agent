"""Runs the real pipeline (via the live HTTP API) against every file in
eval/sample_reports/, scores the output against eval/gold_labels.json, and
writes eval/eval_results.md.

Requires a running backend with a valid GEMINI_API_KEY (this script makes
real network calls through the API -- it does not mock anything, and spends
real API credit, so run it deliberately). Usage:

    python eval/run_eval.py --api-base http://127.0.0.1:8000
"""
import argparse
import json
import time
from pathlib import Path

import requests

HERE = Path(__file__).resolve().parent
SAMPLES_DIR = HERE / "sample_reports"
GOLD_PATH = HERE / "gold_labels.json"
RESULTS_PATH = HERE / "eval_results.md"

CONTENT_TYPES = {
    ".pdf": "application/pdf",
    ".png": "image/png",
    ".jpg": "image/jpeg",
    ".jpeg": "image/jpeg",
    ".txt": "text/plain",
}


def upload_and_wait(api_base: str, file_path: Path, timeout_s: int = 120) -> dict:
    content_type = CONTENT_TYPES[file_path.suffix.lower()]
    with open(file_path, "rb") as f:
        resp = requests.post(
            f"{api_base}/reports",
            files={"file": (file_path.name, f, content_type)},
        )
    resp.raise_for_status()
    doc_id = resp.json()["id"]

    start = time.time()
    while time.time() - start < timeout_s:
        detail = requests.get(f"{api_base}/reports/{doc_id}").json()
        if detail["status"] in ("complete", "failed"):
            return detail
        time.sleep(1.5)
    raise TimeoutError(f"{file_path.name} did not finish processing within {timeout_s}s")


def score_document(expected_tests: list[dict], observations: list[dict]) -> dict:
    obs_by_name = {o["original_test_name"].strip().lower(): o for o in observations}

    extraction_hits = 0
    mapping_hits = 0
    rows = []

    for exp in expected_tests:
        key = exp["original_test_name"].strip().lower()
        obs = obs_by_name.get(key)
        extracted_ok = obs is not None and str(obs.get("value")) == str(exp.get("value"))
        if extracted_ok:
            extraction_hits += 1

        if "expect_mapping_status_in" in exp:
            mapping_ok = obs is not None and obs.get("mapping_status") in exp["expect_mapping_status_in"]
        else:
            mapping_ok = obs is not None and obs.get("loinc_code") == exp.get("loinc_code")
        if mapping_ok:
            mapping_hits += 1

        rows.append({
            "test": exp["original_test_name"],
            "expected_loinc": exp.get("loinc_code"),
            "got_loinc": obs.get("loinc_code") if obs else None,
            "mapping_status": obs.get("mapping_status") if obs else "MISSING",
            "extracted_ok": extracted_ok,
            "mapping_ok": mapping_ok,
        })

    n = len(expected_tests)
    return {
        "n_expected": n,
        "extraction_accuracy": extraction_hits / n if n else None,
        "mapping_accuracy": mapping_hits / n if n else None,
        "rows": rows,
    }


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--api-base", default="http://127.0.0.1:8000")
    args = parser.parse_args()

    gold = json.loads(GOLD_PATH.read_text(encoding="utf-8"))

    report_lines = [
        "# Evaluation Results",
        "",
        f"Generated by `eval/run_eval.py` against a live backend at `{args.api_base}`.",
        "These numbers come from an actual pipeline run against real LLM API calls; nothing here is hand-written.",
        "",
    ]

    total_extraction = []
    total_mapping = []

    for case in gold:
        file_path = SAMPLES_DIR / case["file"]
        print(f"Processing {file_path.name} ...")
        try:
            detail = upload_and_wait(args.api_base, file_path)
        except Exception as e:
            report_lines.append(f"## {case['file']}\n\n**PIPELINE ERROR:** {e}\n")
            continue

        if detail["status"] == "failed":
            report_lines.append(
                f"## {case['file']}\n\n**Document processing FAILED:** {detail.get('error_message')}\n"
            )
            continue

        score = score_document(case["expected"], detail["observations"])
        total_extraction.append(score["extraction_accuracy"])
        total_mapping.append(score["mapping_accuracy"])

        report_lines.append(f"## {case['file']}  ({case['format']}, {case['quality']})")
        report_lines.append("")
        report_lines.append(f"- Extraction accuracy: {score['extraction_accuracy']:.0%}")
        report_lines.append(f"- LOINC mapping accuracy: {score['mapping_accuracy']:.0%}")
        report_lines.append("")
        report_lines.append("| Test | Expected LOINC | Got LOINC | Mapping Status | Extracted OK | Mapping OK |")
        report_lines.append("|---|---|---|---|---|---|")
        for row in score["rows"]:
            report_lines.append(
                f"| {row['test']} | {row['expected_loinc']} | {row['got_loinc']} | "
                f"{row['mapping_status']} | {'✅' if row['extracted_ok'] else '❌'} | "
                f"{'✅' if row['mapping_ok'] else '❌'} |"
            )
        report_lines.append("")

    if total_extraction:
        overall_extraction = sum(total_extraction) / len(total_extraction)
        overall_mapping = sum(total_mapping) / len(total_mapping)
        report_lines.insert(4, f"**Overall extraction accuracy: {overall_extraction:.1%}**  ")
        report_lines.insert(5, f"**Overall LOINC mapping accuracy: {overall_mapping:.1%}**")
        report_lines.insert(6, "")

    RESULTS_PATH.write_text("\n".join(report_lines), encoding="utf-8")
    print(f"\nWrote {RESULTS_PATH}")


if __name__ == "__main__":
    main()
